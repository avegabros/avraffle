const fs = require('fs');
const path = require('path');

const versionConfigPath = path.resolve(__dirname, '../version.json');
const versionData = JSON.parse(fs.readFileSync(versionConfigPath, 'utf8'));

const versionString = `${versionData.version}+${versionData.buildNumber}`;
console.log(`Syncing unified version: ${versionString} across app and web...`);

// 1. Sync mobile/pubspec.yaml
const pubspecPath = path.resolve(__dirname, '../mobile/pubspec.yaml');
if (fs.existsSync(pubspecPath)) {
  let pubspec = fs.readFileSync(pubspecPath, 'utf8');
  pubspec = pubspec.replace(/^version:\s*.*$/m, `version: ${versionString}`);
  fs.writeFileSync(pubspecPath, pubspec, 'utf8');
  console.log(`Updated mobile/pubspec.yaml -> version: ${versionString}`);
}

// 2. Sync mobile/lib/version.dart for in-app UI display
const dartVersionPath = path.resolve(__dirname, '../mobile/lib/version.dart');
const dartCode = `// Auto-generated by scripts/sync-version.js from version.json
class AppVersion {
  static const String version = '${versionData.version}';
  static const int buildNumber = ${versionData.buildNumber};
  static const String full = 'v${versionData.version}';
  static const String buildInfo = 'v${versionData.version} (Build ${versionData.buildNumber})';
}
`;
fs.writeFileSync(dartVersionPath, dartCode, 'utf8');
console.log(`Updated mobile/lib/version.dart -> ${versionData.version}`);

// 3. Sync web/src/lib/version.ts for web & landing page UI
const webVersionPath = path.resolve(__dirname, '../web/src/lib/version.ts');
const webCode = `// Auto-generated by scripts/sync-version.js from version.json
export const APP_VERSION = {
  version: '${versionData.version}',
  buildNumber: ${versionData.buildNumber},
  releaseDate: '${versionData.releaseDate}',
  tag: 'v${versionData.version}',
  full: 'v${versionData.version} (Build ${versionData.buildNumber})',
  package: '${versionData.package}',
};
`;
fs.writeFileSync(webVersionPath, webCode, 'utf8');
console.log(`Updated web/src/lib/version.ts -> ${versionData.version}`);

console.log('Version sync completed successfully!');
